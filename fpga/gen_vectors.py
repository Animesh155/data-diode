"""
gen_vectors.py — emit golden CRC test vectors from the Python reference model.

The Verilog CRC unit must agree byte-for-byte with frame.py (which uses
zlib.crc32 = CRC-32/ISO-HDLC). This script builds real batch datagrams with
build_batch(), extracts the exact byte range the CRC covers, and writes a
Verilog include file the testbench consumes.

CRC region per WIRE_FORMAT.md: bytes [2 .. 14+7*COUNT) — VERSION through the
last record. SYNC and the CRC field itself are excluded.

Run:  python3 gen_vectors.py
Out:  tb/crc_vectors.vh
"""

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "phase1_env", "ot_proxy"))

import frame
from frame import build_batch, BATCH_HEADER_SIZE, RECORD_SIZE

MAX_BYTES = 4096


def crc_region(datagram: bytes, count: int) -> bytes:
    """The exact bytes the CRC is computed over."""
    body_end = BATCH_HEADER_SIZE + count * RECORD_SIZE
    return datagram[2:body_end]


FRAME_MAXB = 16384

# ── Per-tag engineering limits (the hardware policy table) ──────────────────
# These are the bounds tag_policy.v enforces in gates. Ranges below are derived
# from observed HAI replay values with headroom; a real deployment must set
# them from the actual instrument spec, not from observed data.
# tag_id -> (min, max)
TAG_LIMITS = {
    0x0101: (0.0,    1000.0),   # P1_FT01_intake_flow_1
    0x0102: (0.0,    5000.0),   # P1_FT01Z_intake_flow_1z
    0x0103: (0.0,    5000.0),   # P1_FT02_transfer_flow
    0x0104: (0.0,    1000.0),   # P1_FT03_output_flow
    0x0105: (0.0,    1500.0),   # P1_LIT01_tank_level
    0x0106: (0.0,     100.0),   # P1_LCV01D_lvl_valve_D
    0x0107: (0.0,     100.0),   # P1_LCV01Z_lvl_valve_Z
    0x0108: (0.0,      50.0),   # P1_PIT01_pressure_1
    0x0109: (0.0,      50.0),   # P1_PIT02_pressure_2
    0x010A: (0.0,     100.0),   # P1_PCV01D_press_valve_D
    0x010B: (0.0,     100.0),   # P1_PCV01Z_press_valve_Z
    0x010C: (-50.0,   200.0),   # P1_TIT01_temperature_1
    0x010D: (-50.0,   200.0),   # P1_TIT02_temperature_2
    0x010E: (0.0,     100.0),   # P1_FCV03D_flow_valve_D
    0x010F: (0.0,     100.0),   # P1_FCV03Z_flow_valve_Z
    0xFFFF: (0.0,  1.0e9),      # heartbeat: OT proxy uptime in seconds
}


def f32_bits(x: float) -> int:
    """IEEE-754 float32 bit pattern, as the hardware sees it."""
    return struct.unpack('!I', struct.pack('!f', x))[0]


def write_policy_table(path):
    """Emit the tag_policy ROM contents. Single source of truth with software."""
    items = sorted(TAG_LIMITS.items())
    lines = ["// GENERATED by gen_vectors.py - do not edit by hand.",
             "// Per-tag engineering limits enforced by tag_policy.v.",
             "initial begin"]
    for idx, (tag, (lo, hi)) in enumerate(items):
        lines.append(f"  tbl_tag[{idx}] = 16'h{tag:04X};"
                     f"  tbl_min[{idx}] = 32'h{f32_bits(lo):08X};"
                     f"  tbl_max[{idx}] = 32'h{f32_bits(hi):08X};"
                     f"   // {lo} .. {hi}")
    lines.append("end")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {path}")
    print(f"{len(items)} tags in hardware policy table")
    return len(items)


def corrupt(data: bytes, index: int) -> bytes:
    """Flip every bit of one byte — simulates a wire error."""
    b = bytearray(data)
    b[index] ^= 0xFF
    return bytes(b)


def gen_frame_vectors():
    """
    Full-datagram vectors for the frame validator: positive AND negative.

    Each vector is a raw byte stream plus the expected outcome:
      n_done   — how many frames should resolve (accept or drop)
      n_accept — how many of those should be accepted
      last_seq — SEQ of the final accepted frame (0 if none)

    The negative cases are the point: a validator that only ever accepts is
    useless. These prove corruption, bad version, and crafted COUNT are all
    rejected, and that a truncated frame yields no verdict at all rather
    than a false accept.
    """
    # Values must lie inside each tag's engineering limits or tag_policy will
    # (correctly) reject the frame. Use a quarter-scale point in each range.
    def valid_value(tag):
        lo, hi = TAG_LIMITS[tag]
        return lo + (hi - lo) * 0.25

    good_kf = build_batch(seq=42, timestamp=1_700_000_000,
                          records=[(0x0101 + i, valid_value(0x0101 + i), 0x00)
                                   for i in range(15)],
                          keyframe=True)
    good_delta = build_batch(seq=43, timestamp=1_700_000_001,
                             records=[(0x0105, 395.3, 0x00), (0x0108, 1.36, 0x00),
                                      (0x010C, 35.42, 0x00), (0x010F, 52.79, 0x00)])
    good_hb = build_batch(seq=44, timestamp=1_700_000_002,
                          records=[(0xFFFF, 12345.0, 0x00)], heartbeat=True)
    good_empty = build_batch(seq=45, timestamp=1_700_000_003, records=[])
    # Max-size frame: exercises the longest CRC run and the byte counters, so
    # repeat one whitelisted tag rather than inventing 200 unknown ones.
    cap = frame.MAX_RECORDS_PER_DATAGRAM
    good_max = build_batch(seq=47, timestamp=1_700_000_004,
                           records=[(0x0105, 400.0, 0x00)] * cap,
                           keyframe=True)

    # Header-only frames for the checks that fire before any record streams.
    bad_version = bytearray(good_delta[:frame.BATCH_HEADER_SIZE])
    bad_version[2] = 0x03                       # VERSION 3 — unsupported
    crafted_count = bytearray(good_delta[:frame.BATCH_HEADER_SIZE])
    crafted_count[12:14] = (999).to_bytes(2, 'big')   # COUNT far above the cap

    # ── Semantic (tag_policy) cases ─────────────────────────────
    # Structurally perfect frames — correct SYNC, VERSION, COUNT and a valid
    # CRC — that must still be REJECTED because a value is not plausible for
    # the tag it claims to be. This is what separates well-formed from
    # well-behaved, and it is the covert-channel defence.
    over_range = build_batch(seq=50, timestamp=1_700_000_010,
                             records=[(0x0108, 9999.0, 0x00)])       # pressure max 50
    under_range = build_batch(seq=51, timestamp=1_700_000_011,
                              records=[(0x010C, -273.15, 0x00)])     # temp min -50
    nan_val = build_batch(seq=52, timestamp=1_700_000_012,
                          records=[(0x0105, float('nan'), 0x00)])
    inf_val = build_batch(seq=53, timestamp=1_700_000_013,
                          records=[(0x0105, float('inf'), 0x00)])
    unknown_tag = build_batch(seq=54, timestamp=1_700_000_014,
                              records=[(0x0999, 1.0, 0x00)])         # not whitelisted
    # Boundary values must be ACCEPTED — off-by-one in the comparator is the
    # classic bug here.
    at_min = build_batch(seq=55, timestamp=1_700_000_015,
                         records=[(0x010C, -50.0, 0x00)])
    at_max = build_batch(seq=56, timestamp=1_700_000_016,
                         records=[(0x0108, 50.0, 0x00)])
    # One bad record among many good ones must poison the whole frame.
    mixed = build_batch(seq=57, timestamp=1_700_000_017,
                        records=[(0x0101, 200.0, 0x00),
                                 (0x0105, 400.0, 0x00),
                                 (0x0108, 9999.0, 0x00),   # <-- bad
                                 (0x010C, 35.0, 0x00)])

    vecs = [
        # label, stream, n_done, n_accept, last_seq
        ("accept keyframe 15",    good_kf,                       1, 1, 42),
        ("accept delta 4",        good_delta,                    1, 1, 43),
        ("accept heartbeat",      good_hb,                       1, 1, 44),
        ("accept empty COUNT=0",  good_empty,                    1, 1, 45),
        (f"accept max {cap} recs", good_max,                     1, 1, 47),
        # ── negative cases ──────────────────────────────────────
        ("drop corrupt payload",  corrupt(good_kf, 20),          1, 0, 0),
        ("drop corrupt CRC",      corrupt(good_kf, len(good_kf) - 2), 1, 0, 0),
        ("drop bad VERSION",      bytes(bad_version),            1, 0, 0),
        ("drop crafted COUNT",    bytes(crafted_count),          1, 0, 0),
        ("truncated -> no verdict", good_kf[:-2],                0, 0, 0),
        # ── stream behaviour ────────────────────────────────────
        ("resync after garbage",  b"\xDE\xAD\xBE\xEF" + good_delta, 1, 1, 43),
        ("two frames back-to-back", good_kf + good_delta,        2, 2, 43),
        # ── semantic policy: valid CRC, implausible content ─────
        ("drop value over range",  over_range,                   1, 0, 0),
        ("drop value under range", under_range,                  1, 0, 0),
        ("drop NaN value",         nan_val,                      1, 0, 0),
        ("drop Inf value",         inf_val,                      1, 0, 0),
        ("drop unknown tag",       unknown_tag,                  1, 0, 0),
        ("accept value at min",    at_min,                       1, 1, 55),
        ("accept value at max",    at_max,                       1, 1, 56),
        ("drop mixed good+bad",    mixed,                        1, 0, 0),
    ]
    return vecs


def write_frame_vectors(path):
    vecs = gen_frame_vectors()
    total = sum(len(v[1]) for v in vecs)
    if total > FRAME_MAXB:
        raise SystemExit(f"frame vector bytes {total} exceed {FRAME_MAXB}")

    lines = ["// GENERATED by gen_vectors.py - do not edit by hand.",
             "// Full-datagram vectors for frame_validator (positive + negative).",
             f"localparam NFRM = {len(vecs)};",
             f"localparam FMAXB = {FRAME_MAXB};",
             "reg  [7:0]   frm_bytes  [0:FMAXB-1];",
             "integer      frm_start  [0:NFRM-1];",
             "integer      frm_len    [0:NFRM-1];",
             "integer      frm_done   [0:NFRM-1];",
             "integer      frm_accept [0:NFRM-1];",
             "reg  [31:0]  frm_seq    [0:NFRM-1];",
             "reg  [255:0] frm_label  [0:NFRM-1];",
             "initial begin"]

    offset = 0
    for idx, (label, stream, n_done, n_accept, last_seq) in enumerate(vecs):
        lines.append(f"  // {idx}: {label} ({len(stream)} bytes)")
        lines.append(f"  frm_start[{idx}] = {offset};")
        lines.append(f"  frm_len[{idx}] = {len(stream)};")
        lines.append(f"  frm_done[{idx}] = {n_done};")
        lines.append(f"  frm_accept[{idx}] = {n_accept};")
        lines.append(f"  frm_seq[{idx}] = 32'd{last_seq};")
        lines.append(f'  frm_label[{idx}] = "{label}";')
        for i, b in enumerate(stream):
            lines.append(f"  frm_bytes[{offset + i}] = 8'h{b:02X};")
        offset += len(stream)
    lines.append("end")

    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"wrote {path}")
    print(f"{len(vecs)} frame vectors, {total} bytes total")
    for idx, (label, stream, n_done, n_accept, _) in enumerate(vecs):
        print(f"  [{idx}] {label:<26s} {len(stream):>5d} B  done={n_done} accept={n_accept}")


def main():
    vectors = []   # (label, payload_bytes, expected_crc)

    # 1. Canonical CRC-32/ISO-HDLC check value — proves spec compliance.
    #    This is the industry standard check: "123456789" -> 0xCBF43926
    vectors.append(("spec check '123456789'", b"123456789", frame.CRC32_CHECK))

    # 2. Real keyframe: 15 HAI sensors (the live configuration).
    recs15 = [(0x0101 + i, 100.0 + i * 1.5, 0x00) for i in range(15)]
    dg = build_batch(seq=42, timestamp=1_700_000_000, records=recs15, keyframe=True)
    vectors.append(("keyframe 15 records", crc_region(dg, 15), None))

    # 3. Delta batch: a handful of changed tags.
    recs4 = [(0x0105, 395.3, 0x00), (0x0108, 1.36, 0x00),
             (0x010C, 35.42, 0x00), (0x010F, 52.79, 0x00)]
    dg = build_batch(seq=43, timestamp=1_700_000_001, records=recs4)
    vectors.append(("delta 4 records", crc_region(dg, 4), None))

    # 4. Heartbeat: single record, tag 0xFFFF.
    dg = build_batch(seq=44, timestamp=1_700_000_002,
                     records=[(0xFFFF, 12345.0, 0x00)], heartbeat=True)
    vectors.append(("heartbeat 1 record", crc_region(dg, 1), None))

    # 5. Edge: COUNT=0 (header only, no records).
    dg = build_batch(seq=45, timestamp=1_700_000_003, records=[])
    vectors.append(("empty batch", crc_region(dg, 0), None))

    # 6. Edge: quality/COMM_FAIL + negative and zero values.
    recs_edge = [(0x0001, 0.0, 0xFF), (0x0002, -273.15, 0x02),
                 (0xFFFE, 3.4028235e38, 0x01)]
    dg = build_batch(seq=46, timestamp=0xFFFFFFFF, records=recs_edge)
    vectors.append(("edge values", crc_region(dg, 3), None))

    # 7. Edge: maximum MTU-safe batch (200 records) — worst-case length.
    cap = frame.MAX_RECORDS_PER_DATAGRAM
    recs_max = [((i + 1) & 0xFFFF, float(i), 0x00) for i in range(cap)]
    dg = build_batch(seq=47, timestamp=1_700_000_004, records=recs_max, keyframe=True)
    vectors.append((f"max batch {cap} records", crc_region(dg, cap), None))

    # Fill in expected CRCs from the reference implementation.
    resolved = []
    for label, payload, expected in vectors:
        crc = zlib.crc32(payload) & 0xFFFFFFFF
        if expected is not None and crc != expected:
            raise SystemExit(f"reference mismatch on {label}: {crc:08X} != {expected:08X}")
        resolved.append((label, payload, crc))

    total = sum(len(p) for _, p, _ in resolved)
    if total > MAX_BYTES:
        raise SystemExit(f"vector bytes {total} exceed MAX_BYTES {MAX_BYTES}")

    out_dir = os.path.join(HERE, "tb")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "crc_vectors.vh")

    lines = []
    lines.append("// GENERATED by gen_vectors.py - do not edit by hand.")
    lines.append("// Golden CRC-32/ISO-HDLC vectors from the Python reference model.")
    lines.append(f"localparam NVEC = {len(resolved)};")
    lines.append(f"localparam MAXB = {MAX_BYTES};")
    lines.append("reg  [7:0]  vec_bytes    [0:MAXB-1];")
    lines.append("integer     vec_start    [0:NVEC-1];")
    lines.append("integer     vec_len      [0:NVEC-1];")
    lines.append("reg  [31:0] vec_expected [0:NVEC-1];")
    lines.append("initial begin")

    offset = 0
    for idx, (label, payload, crc) in enumerate(resolved):
        lines.append(f"  // vector {idx}: {label} ({len(payload)} bytes)")
        lines.append(f"  vec_start[{idx}] = {offset};")
        lines.append(f"  vec_len[{idx}] = {len(payload)};")
        lines.append(f"  vec_expected[{idx}] = 32'h{crc:08X};")
        for i, b in enumerate(payload):
            lines.append(f"  vec_bytes[{offset + i}] = 8'h{b:02X};")
        offset += len(payload)
    lines.append("end")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"wrote {out_path}")
    print(f"{len(resolved)} vectors, {total} bytes total")
    for idx, (label, payload, crc) in enumerate(resolved):
        print(f"  [{idx}] {label:<28s} {len(payload):>5d} B  crc=0x{crc:08X}")

    print()
    n_tags = write_policy_table(os.path.join(out_dir, "tag_policy_table.vh"))
    print()
    write_frame_vectors(os.path.join(out_dir, "frame_vectors.vh"))
    print()
    print(f"NOTE: instantiate frame_validator with N_TAGS={n_tags}")


if __name__ == "__main__":
    main()
